"""
Desktop integration for the Claude Code WebUI.

Creates Start Menu / Desktop shortcuts ("Claude Code WebUI") that launch the
app via start_app.pyw (pythonw — zero console windows): it boots the server
if needed, then opens the Edge/Chrome --app desktop window. The shortcut
carries a dedicated app icon (app.ico, generated by make_icon.py).

Usage:
  python install_app.py            # create/refresh shortcuts
  python install_app.py --uninstall
"""
import os
import subprocess
import sys
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent
ICON = APP_DIR / "app.ico"
LAUNCHER = APP_DIR / "start_app.pyw"


def _pythonw() -> str:
    exe = Path(sys.executable)
    pythonw = exe.with_name("pythonw.exe")
    return str(pythonw if pythonw.is_file() else exe)


def _shortcut_paths():
    paths = []
    appdata = os.environ.get("APPDATA", "")
    userprofile = os.environ.get("USERPROFILE", "")
    if appdata:
        paths.append(Path(appdata) / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Claude Code WebUI.lnk")
    if userprofile:
        paths.append(Path(userprofile) / "Desktop" / "Claude Code WebUI.lnk")
    return paths


def _make_shortcut(lnk_path: Path) -> bool:
    icon = str(ICON) if ICON.exists() else ""
    ps = (
        "$s = (New-Object -ComObject WScript.Shell).CreateShortcut('"
        + str(lnk_path).replace("'", "''") + "'); "
        + "$s.TargetPath = '" + _pythonw().replace("'", "''") + "'; "
        + "$s.Arguments = '" + str(LAUNCHER).replace("'", "''") + "'; "
        + "$s.WorkingDirectory = '" + str(APP_DIR).replace("'", "''") + "'; "
        + "$s.Description = 'Claude Code WebUI'; "
        + ("$s.IconLocation = '" + icon + ",0'; " if icon else "")
        + "$s.Save()"
    )
    try:
        subprocess.run(
            ["powershell", "-NoProfile", "-Command", ps],
            capture_output=True, timeout=30, shell=False,
            creationflags=(subprocess.CREATE_NO_WINDOW if os.name == "nt" else 0),
        )
        return lnk_path.exists()
    except Exception:
        return False


def ensure_installed() -> bool:
    if os.name != "nt":
        return False
    if not LAUNCHER.exists():
        print("start_app.pyw missing — cannot install shortcuts")
        return False
    ok = False
    for lnk in _shortcut_paths():
        try:
            lnk.parent.mkdir(parents=True, exist_ok=True)
            if _make_shortcut(lnk):
                print("shortcut created:", lnk)
                ok = True
        except Exception as e:
            print("shortcut failed:", lnk, e)
    return ok


def uninstall() -> None:
    for lnk in _shortcut_paths():
        try:
            if lnk.exists():
                lnk.unlink()
                print("removed:", lnk)
        except OSError as e:
            print("remove failed:", lnk, e)


if __name__ == "__main__":
    if "--uninstall" in sys.argv:
        uninstall()
    else:
        ensure_installed()
